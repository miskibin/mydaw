#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Installs MYDAW's bundled sample content, pinned and checksummed.

.DESCRIPTION
    Reads assets-manifest.json -- the same file the in-app downloader has
    compiled into it -- and makes assets/instruments/<id>/ match it:

      * every sample downloaded from its pinned URL,
      * every file verified against its SHA-256,
      * manifest.json written last, so its presence means the samples beside
        it are complete,
      * ATTRIBUTION.md written, because the content is CC-BY and the licence
        requires the credit to travel with it.

    Idempotent. A file already present at its recorded size is left alone; use
    -Verify to re-hash everything, or -Force to re-download it.

    Every download lands as <name>.part and is renamed onto its final name only
    after its hash matches, so an interrupted run never leaves a truncated
    sample where the loader would decode it.

    assets/ is gitignored. Nothing this script writes is committed.

.PARAMETER Verify
    Re-hash files that are already present, instead of trusting their size.

.PARAMETER Force
    Re-download everything.

.EXAMPLE
    pwsh -File scripts/fetch-assets.ps1

.EXAMPLE
    pwsh -File scripts/fetch-assets.ps1 -Verify
#>
[CmdletBinding()]
param(
    [switch] $Verify,
    [switch] $Force
)

Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'

$RepoRoot     = Split-Path -Parent $PSScriptRoot
$ManifestPath = Join-Path $RepoRoot 'assets-manifest.json'
$AssetsRoot   = Join-Path $RepoRoot 'assets'

if (-not (Test-Path $ManifestPath)) {
    throw "no manifest at $ManifestPath; run scripts/gen-asset-manifest.ps1 first"
}

$manifest = Get-Content -Path $ManifestPath -Raw | ConvertFrom-Json
$installDir = Join-Path $AssetsRoot "instruments/$($manifest.id)"
New-Item -ItemType Directory -Force -Path $installDir | Out-Null

$totalBytes = ($manifest.samples | Measure-Object -Property bytes -Sum).Sum
Write-Host "$($manifest.name): $($manifest.samples.Count) samples, $([math]::Round($totalBytes / 1MB, 1)) MB"
Write-Host "  from $($manifest.source.repo) @ $($manifest.source.commit)"
Write-Host "  licence: $($manifest.source.license)"
Write-Host "  into $installDir"
Write-Host ''

$fetched = 0
$skipped = 0
$index = 0

foreach ($sample in $manifest.samples) {
    $index++
    $path = Join-Path $installDir $sample.file
    $part = "$path.part"

    $present = (Test-Path $path) -and ((Get-Item $path).Length -eq $sample.bytes)
    if ($present -and $Verify) {
        $hash = (Get-FileHash -Path $path -Algorithm SHA256).Hash.ToLowerInvariant()
        if ($hash -ne $sample.sha256.ToLowerInvariant()) {
            Write-Warning "$($sample.file) failed verification; re-fetching"
            Remove-Item -Path $path -Force
            $present = $false
        }
    }
    if ($present -and -not $Force) {
        $skipped++
        continue
    }

    Write-Progress -Activity 'Installing samples' -Status $sample.file `
        -PercentComplete (100 * $index / $manifest.samples.Count)
    Invoke-WebRequest -Uri $sample.url -OutFile $part -UseBasicParsing

    $hash = (Get-FileHash -Path $part -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($hash -ne $sample.sha256.ToLowerInvariant()) {
        Remove-Item -Path $part -Force
        throw "$($sample.file) does not match its pinned checksum (expected $($sample.sha256), got $hash); the download was discarded"
    }
    Move-Item -Path $part -Destination $path -Force
    $fetched++
}
Write-Progress -Activity 'Installing samples' -Completed

# The runtime manifest is the download manifest, verbatim. Unknown fields (url,
# sha256, bytes) are ignored by the loader, and one fewer transformation is one
# fewer thing to get wrong. Written last: its presence means the samples beside
# it are complete.
$runtimeManifest = Join-Path $installDir 'manifest.json'
Copy-Item -Path $ManifestPath -Destination "$runtimeManifest.part" -Force
Move-Item -Path "$runtimeManifest.part" -Destination $runtimeManifest -Force

# CC-BY requires the credit to travel with the content.
$attribution = @"
# Bundled sample content -- attribution

This directory is generated by ``scripts/fetch-assets.ps1``. It is **not** part
of the MYDAW source tree and is excluded from version control; every file here
was downloaded from the pinned source below and verified against a SHA-256
recorded in ``assets-manifest.json``.

## $($manifest.name)

| | |
| --- | --- |
| Author | $($manifest.source.author) |
| Source | <$($manifest.source.repo)> |
| Pinned commit | ``$($manifest.source.commit)`` |
| Licence | [$($manifest.source.license)]($($manifest.source.license_url)) |

> $($manifest.attribution)

$($manifest.source.license) is an **attribution** licence: any distribution of
this content, or of a work built from it, must carry the credit above. MYDAW
does not redistribute these files -- it downloads them from the source named
here -- but anything you export that contains their sound does.

Only a subset of the upstream instrument is installed: $($manifest.samples.Count)
files, being every sampled note at $(($manifest.samples | Group-Object vel_lo).Count)
of the sixteen recorded velocity layers. The upstream release is the complete
set. Samples are truncated to $($manifest.max_seconds) s at load with a
$($manifest.fade_out_seconds) s fade; the files on disk are whole.
"@
Set-Content -Path (Join-Path $AssetsRoot 'ATTRIBUTION.md') -Value $attribution -Encoding utf8NoBOM

Write-Host ''
Write-Host "Done: $fetched fetched, $skipped already present."
Write-Host "  $runtimeManifest"
Write-Host "  $(Join-Path $AssetsRoot 'ATTRIBUTION.md')"
